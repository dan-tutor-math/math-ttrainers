VERB = re.compile(r'\b(выпишите|объясните|приведите|сформулируйте|выскажите|укажите|назовите|составьте|раскройте|поясните|проиллюстрируйте|дайте|опишите|определите|предположите|конкретизируйте|озаглавьте|подтвердите|покажите|докажите|аргументируйте|обоснуйте|выделите|найдите|сравните|охарактеризуйте)\b',re.I)
ABBR = re.compile(r'(?:\b[А-ЯЁA-Z]|\bт\. ?[дпе]|\bв|\bвв|\bг|\bгг|\bдр|\bсм|\bст|\bч|\bп|\bн\. ?э|\bтыс|\bмлн|\bмлрд|\bруб)\.$')


def sentences(s):
    # Та же нарезка, что у ОГЭ; добавлены нумерованные требования №25.
    out,cur,par,quo=[], '',0,0
    for i,ch in enumerate(s):
        cur+=ch
        closed=False
        if ch=='(':par+=1
        elif ch==')' and par:par-=1;closed=True
        elif ch=='«':quo+=1
        elif ch=='»' and quo:quo-=1
        rest=s[i+1:]
        end_quote=ch=='»' and len(cur)>1 and cur[-2] in '.?!'
        if not par and not quo and (ch in '.?!' or end_quote or closed):
            if ch=='.' and ABBR.search(cur):continue
            if not rest.strip() or re.match(r'\s+(?:[(А-ЯЁA-Z«]|\d+\))',rest):
                out.append(cur.strip());cur=''
    if cur.strip():out.append(cur.strip())
    return out


def requirements(stem):
    s=re.sub(r'ShowPictureQ\([^)]*\);?', ' ',stem)
    s=re.sub(r'Ответ запишите на бланке ответов[^.]*\.',' ',s)
    s=re.sub(r'\s+',' ',s).strip()
    out,ctx=[],''
    for p in sentences(s):
        if out and (p.startswith('(') or p.startswith('Для этого') or re.match(r'(Сложный план|Количество подпунктов|Каждый пример|Примеры не должны)',p)):
            out[-1]+=' '+p;continue
        bare=re.sub(r'«[^»]*»','«»',p)
        if bare.rstrip(' )').endswith('?') or VERB.search(bare):
            if ctx and re.search(r'\bэт(у|от|о|а|ой|им|их|ого|ими|и)\b',bare,re.I) and not out:p=ctx+' '+p
            out.append(p);ctx=''
        else:ctx=p
    return out


def criteria(n):
    return [list(row) for row in LEVELS[n]] + [['',COMMON]]


def build(source,target):
    core.IMG='soc-ege-long-img'
    demo=source.parent/'demo/ob_11_2027.zip'
    if hashlib.sha256(demo.read_bytes()).hexdigest()!=DEMO_SHA256:
        raise ValueError('Демоверсия изменилась: сначала заново сверить критерии №17–25')
    raw=json.loads((source/'tasks.json').read_text())
    texts=json.loads((source/'texts.json').read_text())
    tasks=[t for t in raw if t.get('num27') in TITLES]
    assert len(tasks)==544 and len({t['id'] for t in tasks})==544
    used={t['text_id']:texts[t['text_id']] for t in tasks if t.get('text_id')}
    outputs=core.media_files(source,tasks,used)
    bank,files={},{}
    for n,title in TITLES.items():
        ts=[t for t in tasks if t['num27']==n]
        sections,groups,pick=core.groups_for(ts)
        protos=[]
        for t in ts:
            q=core.clean(t['stem_html']);r=requirements(t['stem'])
            if not r:raise ValueError(t['id']+': нет требований')
            body=''
            if t.get('text_id'):
                common=core.clean(texts[t['text_id']]['html'])
                common=re.sub(r'<p>\s*Прочитайте текст и выполните задания\.?\s*</p>\s*','',common,count=1)
                label='Тема доклада' if n in (24,25) else 'Текст к заданиям 17–20'
                body='<details class="soc-text-box" open><summary>'+label+'</summary><div class="soc-text-body">'+common+'</div></details>'
            body+=q
            if any(core.IMG+'/'+Path(path).name not in body for path in t.get('images',[])):
                raise ValueError(t['id']+': потеряно место рисунка')
            req=''.join('<label class="soc-req"><input type="checkbox"><span>'+html.escape(x,quote=False)+'</span></label>' for x in r)
            p={'id':t['id'],'fipi':t['id'],'proof':True,'q':q,'r':r,'s':'','h':int(t.get('conf27')=='heur'),
               'peek':core.peek(q),'group':pick[t['id']], 'text':'<div class="soc-text">'+body+'</div>',
               'steps':['<b>Что должно быть в ответе</b>'+req], 'criteria':criteria(n)}
            if t.get('text_id'):p['t']=t['text_id']
            protos.append(p)
        rank={g['id']:i for i,g in enumerate(groups)}
        protos.sort(key=lambda p:(rank[p['group']],p['id']))
        name='soc-ege-long-fipi%d.js'%n;files[str(n)]=name
        expr="window.SOC_EGE_LONG_FIPI.tasks['%d']"%n
        data={'sections':sections,'groups':groups,'protos':protos,'criteria':criteria(n)}
        flag="if(new URLSearchParams(location.search).get('all')==='1'){("+expr+").protos.forEach(p=>{if(p.h)p.text='<div class=\"soc-note\">h: номер определён эвристикой</div>'+p.text;});}\n"
        outputs[name]='/* Собрано tools/soc_ege_long_export.py; без образцов ответов. */\n'+expr+' = '+core.js(data)+';\n'+flag
        bank[str(n)]={'title':title,'part':2,'points':POINTS[n],'protos':[dict(protos[0],src=core.SOURCE)]}
    outputs['soc-ege-long-bank.js']='/* КИМ ЕГЭ обществознания 2027, часть 2. */\nwindow.SOC_EGE_LONG_BANK = '+core.js({'tasks':bank})+';\n'+"if(new URLSearchParams(location.search).get('all')==='1')Object.values(SOC_EGE_LONG_BANK.tasks).forEach(t=>t.protos.forEach(p=>{if(p.h)p.text='<div class=\"soc-note\">h: номер определён эвристикой</div>'+p.text;}));\n"
    outputs['soc-ege-long-fipi.js']='/* Развёрнутые задания ФИПИ. Критерии — demo/ob_11_2027.zip, ДЕМО, с.19–33. */\nwindow.SOC_EGE_LONG_FIPI = '+core.js({'source':core.SOURCE,'proj':core.PROJ,'criteriaSource':{'archive':'demo/ob_11_2027.zip','sha256':DEMO_SHA256,'pages':'19–33'},'files':files,'tasks':{}})+';\n'
