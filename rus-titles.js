// Единое название текста в тренажёрах по русскому (изложение №1, сочинение №13):
// «Н.П. Крыщук. «Испытания ждут дружбу всегда…»» — так тексты называют учителя и
// эксперты ОГЭ, по такому названию их узнают и ищут.
// ФИПИ даёт автора только подписью «(По Ю.М. Нагибину*)» — в дательном падеже,
// а в названии нужен именительный, поэтому фамилию переводим здесь.
(function(){
  // фамилии, которые общими правилами не перевести: мужское «-ому» не всегда «-ий»,
  // «Толстой» в дательном — это женская фамилия, «-ке» — женская «-ка»
  const EXC = {
    'Толстому': 'Толстой', 'Толстой': 'Толстая', 'Горькому': 'Горький',
    'Чепилке': 'Чепилка',
  };
  function nomPart(w){
    if (EXC[w]) return EXC[w];
    let m;
    if ((m = w.match(/^(.+[сц]к)ому$/))) return m[1] + 'ий';
    if ((m = w.match(/^(.+[сц]к)ой$/))) return m[1] + 'ая';
    if ((m = w.match(/^(.+(?:ов|ев|ёв|ин|ын))ой$/))) return m[1] + 'а';
    if ((m = w.match(/^(.+[оеё])ю$/))) return m[1] + 'й';        // Рою → Рой
    if ((m = w.match(/^(.+[бвгджзклмнпрстфхцчшщ])ю$/))) return m[1] + 'ь'; // Кассилю → Кассиль
    if ((m = w.match(/^(.+[бвгджзклмнпрстфхцчшщ])у$/))) return m[1]; // Нагибину → Нагибин
    // несклоняемые (Лубенец, Бруштейн) остаются как есть
    return w;
  }
  // «(По К. Г. Паустовскому*)» → «К.Г. Паустовский»; «По материалам интернета» → ''
  function author(s){
    s = String(s || '').replace(/[()*]/g, '').trim().replace(/^По\s+/, '');
    const m = s.match(/^((?:[А-ЯЁ]\.\s*)*)([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)*)$/);
    if (!m) return '';
    return (m[1] ? m[1].replace(/\s+/g, '') + ' ' : '') + m[2].split('-').map(nomPart).join('-');
  }
  // первые слова первого предложения: пяти хватает, чтобы узнать текст.
  // В изложении текст — целый абзац, поэтому сначала отрезаем первое предложение;
  // конец предложения — знак после строчной буквы, чтобы инициалы «А.С.» не резали
  function words(s, n){
    n = n || 5;
    s = String(s || '').replace(/^[\s–—\-]+/, '');
    const end = s.match(/^.*?[а-яёa-z0-9»)][.!?…]+(?=\s+[–—«"(]?[А-ЯЁA-Z0-9])/);
    if (end) s = end[0];
    // реплика в кавычках, обрезанная по предложению, оставляет лишнюю «»»
    if ((s.match(/»/g) || []).length > (s.match(/«/g) || []).length) s = s.replace(/»$/, '');
    const all = s.split(/\s+/).filter(Boolean);
    const cut = all.slice(0, n).join(' ').replace(/[\s.,;:–—\-]+$/, '');
    return cut + (all.length > n ? '…' : '');
  }
  function title(au, sentence){
    const a = author(au), w = words(sentence);
    return (a ? a + '. ' : '') + (w ? '«' + w + '»' : '');
  }
  window.RusTitles = { author, words, title };
})();
