GRADES = ["g5", "g6", "g7", "g8", "g9", "g10", "g11"]
TITLES = {g: g[1:] + " класс" for g in GRADES}
LIVE_COUNTS = {"g5": 7, "g6": 7, "g7": 1, "g8": 1, "g9": 4, "g10": 2, "g11": 2}


def parse_spec():
    """{grade: [(block, [("stub", name) | ("live", id)])]}"""
    out, grade, blocks = {}, None, None
    for line in SPEC.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("## "):
            blocks.append((line[3:], []))
        elif line.startswith("# "):
            grade = line[2:]
            blocks = out.setdefault(grade, [])
        # разделитель — « | » с пробелами: в названиях тем есть модуль «|x|»
        elif " | " in line:
            blocks[-1][1].extend(("live", i) for i in line.rsplit(" | ", 1)[1].split())
        else:
            blocks[-1][1].append(("stub", line))
    return out


@contextlib.contextmanager
def local_server():
    proc = subprocess.Popen(
        [sys.executable, "-m", "http.server", str(PORT)], cwd=HERE,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    try:
        for _ in range(50):
            try:
                conn = http.client.HTTPConnection("127.0.0.1", PORT, timeout=0.2)
                conn.request("GET", "/index.html")
                conn.getresponse()
                break
            except Exception:
                time.sleep(0.1)
        else:
            raise RuntimeError("локальный сервер не поднялся")
        yield
    finally:
        proc.terminate()


FAILS = []


def check(cond, msg):
    print(("  ок  " if cond else "  ОШИБКА  ") + msg)
    if not cond:
        FAILS.append(msg)


SECTIONS = """() => [...document.querySelectorAll('#topics .grade-section')].map(s => ({
  heads: s.querySelectorAll('.grade-head').length,
  blocks: [...s.querySelectorAll('.topic')].map(t => ({
    title: t.querySelector('.section-title').textContent.trim(),
    items: [...t.querySelectorAll('.topic-item')].map(e => ({
      tag: e.tagName, name: e.querySelector('.item-name').textContent, href: e.getAttribute('href'),
      soon: e.classList.contains('soon'), label: (e.querySelector('.item-soon')||{}).textContent || '' })) })) }))"""
ITEMS = """() => [...document.querySelectorAll('#topics .topic-item')].map(e => ({
  href: e.getAttribute('href'), name: e.querySelector('.item-name').textContent,
  soon: e.classList.contains('soon') }))"""


def main():
    spec = parse_spec()
    check(list(spec) == GRADES, f"в SPEC семь классов: {list(spec)}")
    errors = []
    with local_server(), sync_playwright() as p:
        b = p.chromium.launch()

        def new_ctx(w=1100, h=900, theme="light", nav_state=None):
            ctx = b.new_context(viewport={"width": w, "height": h})
            ctx.route("https://**/*", lambda r: r.abort())
            init = f"try{{if(!localStorage.getItem('theme'))localStorage.setItem('theme','{theme}');"
            if nav_state is not None:
                init += (f"if(!sessionStorage.getItem('_seeded')){{sessionStorage.setItem('_seeded','1');"
                         f"localStorage.setItem('ogeNav:state', {json.dumps(json.dumps(nav_state))});}}")
            init += "}catch(e){}"
            ctx.add_init_script(init)
            return ctx

        def new_page(ctx, errs=errors):
            pg = ctx.new_page()
            pg.on("pageerror", lambda e: errs.append(f"{pg.url}: {e}"))
            return pg

        def go(pg, path="/index.html"):
            pg.goto(BASE + path, wait_until="domcontentloaded")
            pg.wait_for_selector("#mainTabs .nav-tab")
            pg.wait_for_timeout(150)

        def open_sub(pg, sid):
            pg.click('.nav-tab[data-id="grades"]')
            pg.click(f'.nav-subtab[data-id="{sid}"]')
            pg.wait_for_timeout(120)

        ctx = new_ctx()
        pg = new_page(ctx)
        go(pg)
        trainers = pg.evaluate("Object.fromEntries(Object.entries(TRAINERS).map(([k, v]) => [k, v.href]))")
        all_stub_names = set()

        print("1–2. классы по очереди: блоки, темы, заглушки")
        for g in GRADES:
            open_sub(pg, g)
            label = pg.inner_text(f'.nav-subtab[data-id="{g}"]').replace(" ", " ")
            check(label == f"{TITLES[g]} · {LIVE_COUNTS[g]}", f"{g}: подвкладка «{label}»")
            secs = pg.evaluate(SECTIONS)
            check(len(secs) == 1 and secs[0]["heads"] == 0, f"{g}: одна секция без подзаголовка класса")
            blocks = secs[0]["blocks"] if secs else []
            check([bl["title"] for bl in blocks] == [t for t, _ in spec[g]],
                  f"{g}: блоки по порядку ({len(blocks)})")
            ok_items, bad = True, []
            for (bt, exp), bl in zip(spec[g], blocks):
                got = bl["items"]
                if len(got) != len(exp):
                    ok_items = False
                    bad.append(f"{bt}: {len(got)} вместо {len(exp)}")
                    continue
                for (kind, val), it in zip(exp, got):
                    if kind == "stub":
                        good = (it["soon"] and it["tag"] == "DIV" and it["href"] is None
                                and it["name"] == val and it["label"] == "скоро")
                        all_stub_names.add(val)
                    else:
                        good = (not it["soon"] and it["tag"] == "A" and it["href"] == trainers[val])
                    if not good:
                        ok_items = False
                        bad.append(f"{bt}: {val!r} → {it}")
            check(ok_items, f"{g}: темы и живые на своих местах " + ("" if ok_items else str(bad[:3])))
            n_stub = sum(1 for _, e in spec[g] for k, _ in e if k == "stub")
            check(pg.locator("#topics .topic-item.soon").count() == n_stub, f"{g}: заглушек {n_stub}")
            st = pg.eval_on_selector("#topics .topic-item.soon", "e => [getComputedStyle(e).opacity, getComputedStyle(e).pointerEvents]")
            url0 = pg.url
            box = pg.locator("#topics .topic-item.soon").nth(1).bounding_box()
            pg.mouse.click(box["x"] + box["width"] / 2, box["y"] + box["height"] / 2)
            pg.locator("#topics .topic-item.soon").last.click(force=True)
            pg.wait_for_timeout(200)
            check(float(st[0]) < 1 and st[1] == "none" and pg.url == url0,
                  f"{g}: заглушки приглушены и щелчок никуда не ведёт")

        print("3. живые тренажёры открываются из своей плашки")
        opened = {}
        for g in GRADES:
            ids = [v for _, e in spec[g] for k, v in e if k == "live"]
            for tid in ids:
                go(pg)
                open_sub(pg, g)
                href = trainers[tid]
                errs = []
                pg.on("pageerror", lambda e, errs=errs: errs.append(str(e)))
                pg.click(f'#topics a.topic-item[href="{href}"]')
                pg.wait_for_load_state("domcontentloaded")
                pg.wait_for_timeout(500)
                ok = pg.url.endswith("/" + href) and not errs
                opened.setdefault(tid, []).append(g)
                check(ok, f"{g}: {tid} → {href}" + (f" {errs[:1]}" if errs else ""))
        check(opened.get("percent") == ["g5", "g6"] and opened.get("frac_mul") == ["g5", "g6"]
              and opened.get("frac_div") == ["g5", "g6"], "percent, frac_mul, frac_div открыты и из 5, и из 6 класса")
        check(opened.get("trig_equations") == ["g10", "g11"] and opened.get("logarithms") == ["g10", "g11"],
              "trig_equations и logarithms открыты и из 10, и из 11 класса")
        check(trainers["trig_equations"] == "trig_equations.html", "слаг trig_equations с подчёркиванием")

        print("4–5. счётчики и «1–4 классы»")
        go(pg)
        grades_tab = pg.inner_text('.nav-tab[data-id="grades"]').replace(" ", " ")
        check(grades_tab == "Классы · 25", f"вкладка «{grades_tab}»")
        open_sub(pg, "g1_4")
        heads = pg.eval_on_selector_all("#topics .grade-head", "els => els.map(e => e.textContent.trim())")
        items = pg.evaluate(ITEMS)
        check(heads == ["1 класс", "2 класс", "3 класс", "4 класс"], f"«1–4 классы»: подзаголовки {heads}")
        check(len(items) == 88 and [i["href"] for i in items if not i["soon"]] == ["sostav.html"],
              f"«1–4 классы»: 88 тем, живой только состав числа ({len(items)})")
        all_stub_names |= {i["name"] for i in items if i["soon"]}

        print("6. заглушек нет в «Основе», экзаменах и панели досок")
        pg.click('.nav-tab[data-id="base"]')
        pg.wait_for_timeout(120)
        items = pg.evaluate(ITEMS)
        check(len(items) == 13 and not any(i["soon"] for i in items), f"«Основа»: 13 живых, заглушек нет ({len(items)})")
        pg.click('.nav-tab[data-id="exams"]')
        for sid in pg.eval_on_selector_all("#subTabs .nav-subtab", "els => els.map(e => e.dataset.id)"):
            pg.click(f'.nav-subtab[data-id="{sid}"]')
            pg.wait_for_timeout(100)
            items = pg.evaluate(ITEMS)
            names = {i["name"] for i in items}
            check(not (names & all_stub_names) and pg.locator("#topics .grade-section").count() == 0,
                  f"экзамены → {sid}: заглушек программы нет ({len(items)} строк)")
        pg.add_script_tag(url=BASE + "/trainer-tasks.js")
        panel = pg.evaluate("() => TRAINERS_PANEL_GROUPS.flatMap(g => g.items.map(i => ({name: i.name, href: i.href})))")
        check(len(panel) > 10 and all(i["href"] for i in panel) and not any(i["name"] in all_stub_names for i in panel),
              f"панель досок: только живые, заглушек нет ({len(panel)})")
        ctx.close()

        print("7. сохранённая подвкладка")
        for g in ("g6", "g10"):
            ctx = new_ctx(nav_state={"tabId": "grades", "subtabId": g})
            pg = new_page(ctx)
            go(pg)
            act = pg.eval_on_selector_all(".nav-tab.active, .nav-subtab.active", "els => els.map(e => e.dataset.id)")
            n = pg.locator("#topics .topic").count()
            check(act == ["grades", g] and n == len(spec[g]), f"сохранённая {g} открылась ({act}, блоков {n})")
            pg.reload(wait_until="domcontentloaded")
            pg.wait_for_timeout(150)
            act = pg.eval_on_selector_all(".nav-tab.active, .nav-subtab.active", "els => els.map(e => e.dataset.id)")
            check(act == ["grades", g], f"{g} и после перезагрузки")
            ctx.close()

        print("8. тёмная тема и телефон")
        for w in (375, 320):
            for theme in ("light", "dark"):
                ctx = new_ctx(w=w, h=800, theme=theme, nav_state={"tabId": "grades", "subtabId": "g5"})
                pg = new_page(ctx)
                go(pg)
                bad_all = []
                for g in GRADES:
                    open_sub(pg, g)
                    sw = pg.evaluate("document.documentElement.scrollWidth")
                    bad = pg.evaluate("""() => [...document.querySelectorAll('#topics .topic-item.soon')].filter(e => {
                        const r = e.getBoundingClientRect(), n = e.querySelector('.item-name').getBoundingClientRect(),
                              s = e.querySelector('.item-soon').getBoundingClientRect();
                        return n.right > s.left + 0.5 || s.right > r.right + 0.5 || r.right > innerWidth + 0.5;
                      }).length""")
                    titles_ok = pg.evaluate("() => [...document.querySelectorAll('#topics .section-title')].every(e => e.getBoundingClientRect().right <= innerWidth + 0.5)")
                    if sw > w or bad or not titles_ok:
                        bad_all.append((g, sw, bad, titles_ok))
                check(not bad_all, f"{w}px {theme}: все семь классов без прокрутки вбок и наездов {bad_all}")
                if theme == "dark":
                    col = pg.eval_on_selector("#topics .topic-item.soon .item-name", "e => getComputedStyle(e).color")
                    rgb = [int(x) for x in col[col.index("(") + 1:col.index(")")].split(",")[:3]]
                    check(sum(rgb) / 3 > 170, f"{w}px dark: текст тем светлый ({col})")
                ctx.close()

        print("9. ошибки JavaScript")
        check(not errors, f"ошибок нет: {errors[:3]}")
        b.close()

    print(f"\nИтого: ошибок {len(FAILS)}")
    sys.exit(1 if FAILS else 0)


if __name__ == "__main__":
    main()
